// Two deterministic ordinary-Node outputs; management contains no SDK imports.
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

import { contractIdentity, digest, inputFiles } from "./build-identity.mjs";

const root = resolve(import.meta.dirname, "..");
const version = JSON.parse(
  readFileSync(join(root, "package.json"), "utf8"),
).version;
const source = digest(
  JSON.stringify(
    inputFiles(root, join(root, "src")).filter(
      ([name]) =>
        ![
          "src/service-cli.mjs",
          "src/service-host.mjs",
          "src/operator-cli.mjs",
          "src/native-build.ts",
        ].includes(name),
    ),
  ),
);
const checking = process.argv.includes("--check");
const temporary = checking
  ? mkdtempSync(join(tmpdir(), "cadence-service-build-"))
  : null;
// Native extensions load TS directly: ship their independently generated local
// compatibility identity rather than trusting the connected service's echo.
const nativeIdentity = `// Generated by scripts/build-service.mjs; do not edit.\nexport const nativeBuild = {\n  kind: "native",\n  contractHash:\n    "${contractIdentity(root)}",\n} as const;\n`;
const nativeTarget = join(root, "src/native-build.ts");
if (checking) {
  if (readFileSync(nativeTarget, "utf8") !== nativeIdentity)
    throw new Error("native-build-stale");
} else writeFileSync(nativeTarget, nativeIdentity);
for (const name of ["service-cli", "service-host"]) {
  const result = await Bun.build({
    entrypoints: [join(root, `src/${name}-entry.mjs`)],
    root,
    target: "node",
    define: {
      __CADENCE_SERVICE_VERSION__: JSON.stringify(version),
      __CADENCE_SERVICE_SOURCE__: JSON.stringify(source),
      __CADENCE_SERVICE_CONTRACT__: JSON.stringify(contractIdentity(root)),
    },
    format: "esm",
    packages: "external",
    sourcemap: "none",
    minify: false,
  });
  if (!result.success || result.outputs.length !== 1)
    throw new Error("service-build-failed");
  const body = await result.outputs[0].text();
  const bytes = `${name === "service-cli" ? "#!/usr/bin/env node\n" : ""}// Generated by scripts/build-service.mjs; edit the entry and source modules.\n${body.replace(/^#![^\n]*\n/, "")}`;
  if (name === "service-cli" && /@earendil-works\//.test(bytes))
    throw new Error("management-sdk-import");
  const target = join(root, `src/${name}.mjs`);
  if (checking) {
    writeFileSync(join(temporary, `${name}.mjs`), bytes);
    if (readFileSync(target, "utf8") !== bytes)
      throw new Error("service-bundle-stale");
  } else writeFileSync(target, bytes, { mode: 0o755 });
}
