// Canonical ordinary JavaScript operator for installed node_modules.
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const target = path.join(root, "src/operator-cli.mjs");
const result = await Bun.build({
  entrypoints: [path.join(root, "src/operator-cli-entry.mjs")],
  root,
  target: "node",
  format: "esm",
  packages: "external",
  sourcemap: "none",
  minify: false,
});
if (!result.success || result.outputs.length !== 1)
  throw new Error("operator-build-failed");
const bytes = `// Generated by scripts/build-operator.mjs; edit operator-cli-entry.mjs and its source modules.\n${await result.outputs[0].text()}`;
if (process.argv.includes("--check")) {
  const temporary = mkdtempSync(path.join(tmpdir(), "cadence-operator-build-"));
  writeFileSync(path.join(temporary, "operator-cli.mjs"), bytes, {
    mode: 0o600,
    flag: "wx",
  });
  if (readFileSync(target, "utf8") !== bytes)
    throw new Error(
      "operator-bundle-stale: run bun scripts/build-operator.mjs",
    );
} else writeFileSync(target, bytes);
