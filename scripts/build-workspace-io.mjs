// The native worker must run inside installed node_modules without TS stripping.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
for (const [source, destination] of [
  ["workspace-io-entry.mjs", "workspace-io-worker.mjs"],
  ["operator-cli-entry.mjs", "operator-cli.mjs"],
]) {
  const target = path.join(root, "src", destination);
  const result = await Bun.build({
    entrypoints: [path.join(root, "src", source)],
    root,
    target: "node",
    format: "esm",
    packages: "external",
    sourcemap: "none",
    minify: false,
  });
  if (!result.success || result.outputs.length !== 1)
    throw new Error("workspace-io-build-failed");
  const bytes = `// Generated by scripts/build-workspace-io.mjs; edit ${source} and its source modules.\n${await result.outputs[0].text()}`;
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== bytes)
      throw new Error(
        "workspace-io-bundle-stale: run bun scripts/build-workspace-io.mjs",
      );
  } else writeFileSync(target, bytes);
}
