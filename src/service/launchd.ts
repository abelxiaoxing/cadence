/** macOS LaunchAgent for the shared owner, loaded at login in the user's GUI
 * domain. launchd only signals its job, so every change first runs the
 * authenticated orderly Stop and refuses unless it is confirmed. There is no
 * KeepAlive: launchd has no start limit, and a restart never clears fences. */
import { rmSync } from "node:fs";
import { join } from "node:path";
import {
  type AutostartResult,
  type AutostartSystem,
  agentDirectory,
  checked,
  readGenerated,
  regularFile,
  sdkPackages,
  selectWorkspace,
  serviceEnvironment,
  settle,
  write,
} from "./autostart.ts";
import { serverConfigPath } from "./server-config.ts";

export const LABEL = "com.abelxiaoxing.cadence";
const MARKER =
  '<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by @abelxiaoxing/cadence';

export function plistPath(s: AutostartSystem): string {
  return join(s.home, "Library", "LaunchAgents", `${LABEL}.plist`);
}
const xml = (value: string) =>
  checked(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");

export interface PlistInput {
  node: string;
  cli: string;
  workspace: string;
  serverConfig: string;
  environment: [string, string][];
  log: string;
}
export function buildPlist(u: PlistInput): string {
  const string = (value: string) => `\t\t<string>${xml(value)}</string>`;
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    "<!-- Generated by @abelxiaoxing/cadence; `cadence server install` and `restart` rewrite this file. -->",
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<plist version="1.0">',
    "<dict>",
    "\t<key>Label</key>",
    `\t<string>${LABEL}</string>`,
    "\t<key>ProgramArguments</key>",
    "\t<array>",
    ...[
      u.node,
      u.cli,
      "start",
      "--foreground",
      "--workspace",
      u.workspace,
      "--server-config",
      u.serverConfig,
    ].map(string),
    "\t</array>",
    "\t<key>WorkingDirectory</key>",
    `\t<string>${xml(u.workspace)}</string>`,
    "\t<key>EnvironmentVariables</key>",
    "\t<dict>",
    ...u.environment.flatMap(([k, v]) => [
      `\t\t<key>${xml(k)}</key>`,
      string(v),
    ]),
    "\t</dict>",
    "\t<key>RunAtLoad</key>",
    "\t<true/>",
    "\t<key>ProcessType</key>",
    "\t<string>Background</string>",
    "\t<key>StandardOutPath</key>",
    `\t<string>${xml(u.log)}</string>`,
    "\t<key>StandardErrorPath</key>",
    `\t<string>${xml(u.log)}</string>`,
    "</dict>",
    "</plist>",
    "",
  ].join("\n");
}
function plistWorkspace(text: string | undefined): string | undefined {
  const m = text?.match(
    /^\t<key>WorkingDirectory<\/key>\n\t<string>([^<]*)<\/string>$/m,
  );
  return m?.[1]
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&amp;", "&");
}
const domain = (s: AutostartSystem) => `gui/${s.uid}`;
const target = (s: AutostartSystem) => `${domain(s)}/${LABEL}`;
const loaded = (s: AutostartSystem) =>
  s.launchctl(["print", target(s)]).status === 0;
/** `launchctl disable` persists across loads until `enable`. */
function disabled(s: AutostartSystem): boolean {
  return new RegExp(
    `"${LABEL.replaceAll(".", "\\.")}" => (true|disabled)`,
  ).test(s.launchctl(["print-disabled", domain(s)]).stdout);
}
/** install: from any package location, also undoing `launchctl disable`.
 * restart: rewrites an existing agent with the current Node and package
 * paths, keeping its workspace and a disable. Both load it, which starts it. */
export async function configureLaunchAgent(
  s: AutostartSystem,
  mode: "install" | "restart",
  requested?: string,
): Promise<AutostartResult> {
  if (s.uid === undefined) return { status: "unavailable" };
  const path = plistPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (mode === "restart" && previous === undefined) return { status: "absent" };
  const sdk = sdkPackages(s.root);
  if (!sdk) return { status: "missing-pi-sdk" };
  const kept = plistWorkspace(previous);
  const { workspace, redirectedFrom } = selectWorkspace(s, requested, kept);
  const refused = await settle(s, kept);
  if (refused) return { ...refused, unit: path };
  // Nothing runs now, so unloading signals no owner.
  if (loaded(s)) s.launchctl(["bootout", target(s)]);
  write(
    path,
    buildPlist({
      node: s.node,
      cli: join(s.root, "src", "service-cli.mjs"),
      workspace,
      serverConfig: serverConfigPath(s.home),
      environment: serviceEnvironment(s),
      log: join(s.home, "Library", "Logs", "cadence.log"),
    }),
  );
  const result = {
    unit: path,
    workspace,
    ...(redirectedFrom ? { redirectedFrom } : {}),
  };
  if (mode === "install") s.launchctl(["enable", target(s)]);
  else if (disabled(s)) return { status: "disabled", ...result };
  // A new owner without Pi's auth source would refuse; the next login loads it.
  if (!regularFile(join(agentDirectory(s), "auth.json")))
    return { status: "waiting-for-pi-login", ...result };
  const started = s.launchctl(["bootstrap", domain(s), path]).status === 0;
  return { status: started ? "started" : "failed", ...result };
}
/** The job exits successfully with its owner and stays loaded for the next login. */
export async function stopLaunchAgent(
  s: AutostartSystem,
): Promise<AutostartResult> {
  const path = plistPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  const workspace = plistWorkspace(previous);
  const refused = await settle(s, workspace);
  return { ...(refused ?? { status: "stopped", workspace }), unit: path };
}
export async function removeLaunchAgent(
  s: AutostartSystem,
): Promise<AutostartResult> {
  const path = plistPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  const refused = await settle(s, plistWorkspace(previous));
  if (refused) return { ...refused, unit: path };
  if (s.uid !== undefined && loaded(s)) s.launchctl(["bootout", target(s)]);
  rmSync(path);
  return { status: "removed", unit: path };
}
export function launchAgentStatus(s: AutostartSystem): AutostartResult {
  const path = plistPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  const printed =
    s.uid === undefined ? undefined : s.launchctl(["print", target(s)]);
  return {
    status:
      printed?.status !== 0
        ? "unloaded"
        : /^\s*state = running$/m.test(printed.stdout)
          ? "active"
          : "inactive",
    enabled: s.uid !== undefined && disabled(s) ? "disabled" : "enabled",
    unit: path,
    workspace: plistWorkspace(previous),
  };
}
