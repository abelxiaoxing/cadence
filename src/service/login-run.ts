/** Windows per-user login start for the shared owner: the user's Run key
 * starts a generated launcher that runs `start` without a console window.
 * Nothing supervises the detached owner afterwards, so every change first runs
 * the authenticated orderly Stop and refuses unless it is confirmed; nothing is
 * killed. Registry values are only tested for presence, because reg.exe
 * prints them in the console code page. */
import { rmSync } from "node:fs";
import { isAbsolute, join } from "node:path";
import { ContractError } from "../service-contract.ts";
import {
  type AutostartResult,
  type AutostartSystem,
  agentDirectory,
  checked,
  readGenerated,
  regularFile,
  sdkPackages,
  selectWorkspace,
  settle,
  write,
  wscript,
} from "./autostart.ts";
import { serverConfigPath } from "./server-config.ts";

export const RUN_KEY =
  "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run";
/** Task Manager's per-entry startup switch for Run values. */
const APPROVED_KEY =
  "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\StartupApproved\\Run";
export const RUN_VALUE = "Cadence";
const MARKER = "' Generated by @abelxiaoxing/cadence";

/** Beside, never inside, the private state home `%LOCALAPPDATA%\cadence-assistant-v1`. */
export function launcherPath(s: AutostartSystem): string {
  const local = s.env.LOCALAPPDATA;
  return join(
    local && isAbsolute(local) ? local : join(s.home, "AppData", "Local"),
    "cadence-server",
    "cadence.vbs",
  );
}
/** A VBScript string literal doubles its quotes. */
const literal = (value: string) => `"${checked(value).replaceAll('"', '""')}"`;
/** Windows paths cannot hold quotes, so one pair delimits each argument. */
function argument(value: string): string {
  if (checked(value).includes('"')) throw new ContractError("invalid");
  return `"${value}"`;
}
export interface LauncherInput {
  node: string;
  cli: string;
  workspace: string;
  serverConfig: string;
  environment: [string, string][];
}
export function buildLauncher(u: LauncherInput): string {
  const command = `${argument(u.node)} ${argument(u.cli)} start --workspace ${argument(u.workspace)} --server-config ${argument(u.serverConfig)}`;
  return [
    `${MARKER}; \`cadence server install\` and \`restart\` rewrite this file.`,
    `' Started at login by ${RUN_KEY}\\${RUN_VALUE}; window style 0 hides the console.`,
    'Set shell = CreateObject("WScript.Shell")',
    // The launched command inherits this process environment.
    ...(u.environment.length ? ['Set env = shell.Environment("Process")'] : []),
    ...u.environment.map(([k, v]) => `env(${literal(k)}) = ${literal(v)}`),
    `shell.CurrentDirectory = ${literal(u.workspace)}`,
    `shell.Run ${literal(command)}, 0, False`,
    "",
  ].join("\r\n");
}
/** Windows Script Host reads non-ANSI paths only from a UTF-16LE script with BOM. */
const utf16 = (text: string) =>
  Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(text, "utf16le")]);
function launcherWorkspace(text: string | undefined): string | undefined {
  return text
    ?.match(/^shell\.CurrentDirectory = "((?:[^"]|"")*)"\r?$/m)?.[1]
    .replaceAll('""', '"');
}
const runEntry = (path: string, s: AutostartSystem) =>
  `"${wscript(s.env)}" "${path}"`;
const present = (s: AutostartSystem, key: string) =>
  s.reg(["query", key, "/v", RUN_VALUE]).status === 0;
/** Task Manager writes an odd first byte (03) for a disabled entry. */
function approvedOff(s: AutostartSystem): boolean {
  const r = s.reg(["query", APPROVED_KEY, "/v", RUN_VALUE]);
  const first = r.status === 0 && /REG_BINARY\s+([0-9A-F]{2})/i.exec(r.stdout);
  return !!first && (Number.parseInt(first[1], 16) & 1) === 1;
}
/** install: registers from any package location, also undoing a Task Manager
 * disable. restart: rewrites an existing launcher with the current Node and
 * package paths, keeping its workspace and Run entry. Both start it now. */
export async function configureLoginRun(
  s: AutostartSystem,
  mode: "install" | "restart",
  requested?: string,
): Promise<AutostartResult> {
  const path = launcherPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  // A Run value without our launcher belongs to something else.
  if (previous === undefined && present(s, RUN_KEY))
    return { status: "foreign", unit: `${RUN_KEY}\\${RUN_VALUE}` };
  if (mode === "restart" && previous === undefined) return { status: "absent" };
  const sdk = sdkPackages(s.root);
  if (!sdk) return { status: "missing-pi-sdk" };
  const kept = launcherWorkspace(previous);
  const { workspace, redirectedFrom } = selectWorkspace(s, requested, kept);
  const refused = await settle(s, kept);
  if (refused) return { ...refused, unit: path };
  // The login environment already carries the user's PATH and %LOCALAPPDATA%.
  const environment: [string, string][] = s.env.PI_CODING_AGENT_DIR
    ? [["PI_CODING_AGENT_DIR", agentDirectory(s)]]
    : [];
  write(
    path,
    utf16(
      buildLauncher({
        node: s.node,
        cli: join(s.root, "src", "service-cli.mjs"),
        workspace,
        serverConfig: serverConfigPath(s.home),
        environment,
      }),
    ),
  );
  const result = {
    unit: path,
    workspace,
    ...(redirectedFrom ? { redirectedFrom } : {}),
  };
  if (mode === "install") {
    const entry = ["/v", RUN_VALUE, "/t", "REG_SZ", "/d", runEntry(path, s)];
    if (s.reg(["add", RUN_KEY, ...entry, "/f"]).status !== 0)
      return { status: "failed", ...result };
    s.reg(["delete", APPROVED_KEY, "/v", RUN_VALUE, "/f"]);
  }
  // A new owner without Pi's auth source would refuse; the next login retries.
  if (!regularFile(join(agentDirectory(s), "auth.json")))
    return { status: "waiting-for-pi-login", ...result };
  return { status: s.launch(path) ? "started" : "failed", ...result };
}
/** The Run entry stays, so the owner starts again at the next login. */
export async function stopLoginRun(
  s: AutostartSystem,
): Promise<AutostartResult> {
  const path = launcherPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  const workspace = launcherWorkspace(previous);
  const refused = await settle(s, workspace);
  return { ...(refused ?? { status: "stopped", workspace }), unit: path };
}
export async function removeLoginRun(
  s: AutostartSystem,
): Promise<AutostartResult> {
  const path = launcherPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  const refused = await settle(s, launcherWorkspace(previous));
  if (refused) return { ...refused, unit: path };
  for (const key of [RUN_KEY, APPROVED_KEY])
    if (present(s, key)) s.reg(["delete", key, "/v", RUN_VALUE, "/f"]);
  rmSync(path);
  return { status: "removed", unit: path };
}
export async function loginRunStatus(
  s: AutostartSystem,
): Promise<AutostartResult> {
  const path = launcherPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  const workspace = launcherWorkspace(previous);
  const owner = workspace ? await s.ownerStatus(workspace) : "unavailable";
  return {
    status: owner === "alive" ? "active" : "inactive",
    enabled: present(s, RUN_KEY) && !approvedOff(s) ? "enabled" : "disabled",
    unit: path,
    workspace,
  };
}
