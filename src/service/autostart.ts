/** Background service registration for the shared owner, written only by the
 * explicit `cadence server` commands: a Linux systemd user unit here, a macOS
 * LaunchAgent (launchd.ts) or a Windows login Run entry (login-run.ts).
 * Management-only and SDK-free: it writes one generated definition and drives
 * the platform's own tool; it never signals owners, edits state homes, deletes
 * locks or repairs quarantine. */
import { spawnSync } from "node:child_process";
import {
  lstatSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import {
  delimiter,
  dirname,
  isAbsolute,
  join,
  resolve,
  sep,
  win32,
} from "node:path";
import { ContractError } from "../service-contract.ts";
import { effectiveWorkspace, LANDING_WORKSPACE } from "../task-store.ts";
import { serverConfigPath } from "./server-config.ts";

export const UNIT = "cadence.service";
const MARKER = "# Generated by @abelxiaoxing/cadence";

type Command = { status: number | null; stdout: string };
/** Authenticated owner control for service managers that only signal. */
export interface OwnerControl {
  /** Orderly Stop of the workspace's owner; "stopped" also when none runs.
   * Anything else (unconfirmed, quarantined, unavailable) is not a stop. */
  stopOwner(workspace: string): Promise<string>;
  /** The authenticated status ("alive", "absent", ...) of the workspace's owner. */
  ownerStatus(workspace: string): Promise<string>;
}
export interface AutostartSystem extends OwnerControl {
  platform: NodeJS.Platform;
  env: NodeJS.ProcessEnv;
  home: string;
  node: string;
  /** Package root containing src/service-cli.mjs. */
  root: string;
  unit: string;
  uid: number | undefined;
  systemctl(args: string[]): Command;
  linger(): boolean | undefined;
  /** `loginctl enable-linger` for this user; interactive may ask for a password. */
  enableLinger(interactive: boolean): boolean;
  /** macOS: launchctl, addressed to the user's GUI domain by the caller. */
  launchctl(args: string[]): Command;
  /** Windows: reg.exe against the user's own hive. */
  reg(args: string[]): Command;
  /** Windows: run the generated launcher, which starts the owner without a window. */
  launch(path: string): boolean;
}
/** on: already lingering; enabled: Cadence enabled it now; refused: the attempt
 * needed authorization or failed; off: not attempted. */
export type LingerState = "on" | "enabled" | "off" | "refused";
export interface AutostartResult {
  status: string;
  unit?: string;
  workspace?: string;
  redirectedFrom?: string;
  enabled?: string;
  linger?: LingerState;
}
export function wscript(env: NodeJS.ProcessEnv): string {
  const root = env.SystemRoot;
  return win32.join(
    root && win32.isAbsolute(root) ? root : "C:\\Windows",
    "System32",
    "wscript.exe",
  );
}
export function hostSystem(root: string, owner: OwnerControl): AutostartSystem {
  const run = (command: string, args: string[]) => {
    const r = spawnSync(command, args, {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      windowsHide: true,
    });
    return { status: r.error ? null : r.status, stdout: r.stdout ?? "" };
  };
  return {
    platform: process.platform,
    env: process.env,
    home: homedir(),
    node: process.execPath,
    root,
    unit: UNIT,
    uid: process.getuid?.(),
    systemctl: (args) => run("systemctl", ["--user", ...args]),
    linger: () => {
      const r = run("loginctl", [
        "show-user",
        String(process.getuid?.()),
        "--property=Linger",
        "--value",
      ]);
      return r.status === 0 ? r.stdout.trim() === "yes" : undefined;
    },
    // loginctl always asks logind for an interactive check (--no-ask-password
    // only skips its own terminal agent), which lets a desktop polkit agent
    // open a dialog, so the unprompted attempt calls SetUserLinger with
    // interactive=false and no interactive authorization instead.
    enableLinger: (interactive) => {
      const r = interactive
        ? spawnSync("loginctl", ["enable-linger"], { stdio: "inherit" })
        : spawnSync(
            "busctl",
            [
              "--system",
              "--allow-interactive-authorization=no",
              "--timeout=15",
              "call",
              "org.freedesktop.login1",
              "/org/freedesktop/login1",
              "org.freedesktop.login1.Manager",
              "SetUserLinger",
              "ubb",
              String(process.getuid?.()),
              "true",
              "false",
            ],
            { stdio: "ignore", timeout: 20000 },
          );
      return !r.error && r.status === 0;
    },
    launchctl: (args) => run("launchctl", args),
    reg: (args) => run("reg", args),
    launch: (path) => {
      // The launcher's Run call returns at once; the owner outlives it.
      const r = spawnSync(wscript(process.env), [path], {
        stdio: "ignore",
        windowsHide: true,
        timeout: 20000,
      });
      return !r.error && r.status === 0;
    },
    ...owner,
  };
}
export function expandHome(value: string, home: string): string {
  if (value === "~") return home;
  return value.startsWith("~/") ? join(home, value.slice(2)) : value;
}
/** Same selection as Pi's getAgentDir: PI_CODING_AGENT_DIR or ~/.pi/agent. */
export function agentDirectory(s: AutostartSystem): string {
  const selected = s.env.PI_CODING_AGENT_DIR;
  return resolve(
    selected ? expandHome(selected, s.home) : join(s.home, ".pi", "agent"),
  );
}
/** Pi's user-scope npm layout, whose copy puts no `cadence` bin on PATH. */
export function piUserInstall(s: AutostartSystem): boolean {
  try {
    const managed = join(
      agentDirectory(s),
      "npm",
      "node_modules",
      "@abelxiaoxing",
      "cadence",
    );
    return realpathSync(managed) === realpathSync(s.root);
  } catch {
    return false;
  }
}
/** The host bundle imports these by bare specifier. Pi installs packages with
 * --legacy-peer-deps, so they exist only if something else provides them; an
 * owner that cannot load them quarantines, so never register without them. */
export function sdkPackages(root: string): string[] | undefined {
  let start: string;
  try {
    start = realpathSync(join(root, "src"));
  } catch {
    return undefined;
  }
  const found: string[] = [];
  for (const name of ["pi-coding-agent", "pi-ai"]) {
    let hit: string | undefined;
    for (let dir = start; !hit; dir = dirname(dir)) {
      const candidate = join(
        dir,
        "node_modules",
        "@earendil-works",
        name,
        "package.json",
      );
      if (regularFile(candidate)) hit = candidate;
      else if (dirname(dir) === dir) return undefined;
    }
    found.push(hit);
  }
  return found;
}
/** Package-owned units live in the user data path, so `systemctl --user mask`
 * and `edit` in ~/.config/systemd/user keep overriding what restarts rewrite. */
export function unitPath(s: AutostartSystem): string {
  const data = s.env.XDG_DATA_HOME;
  return join(
    data && isAbsolute(data) ? data : join(s.home, ".local", "share"),
    "systemd",
    "user",
    s.unit,
  );
}
/** npm prepends lifecycle bins to PATH; bake only the user's own search path. */
export function servicePath(value: string | undefined): string {
  const kept = (value ?? "")
    .split(delimiter)
    .filter(
      (entry) =>
        isAbsolute(entry) &&
        !entry.endsWith(`${sep}node_modules${sep}.bin`) &&
        !entry.includes(`${sep}node-gyp-bin`),
    );
  return kept.length
    ? [...new Set(kept)].join(delimiter)
    : "/usr/local/bin:/usr/bin:/bin";
}
/** systemd and launchd start services with a minimal environment. */
export function serviceEnvironment(s: AutostartSystem): [string, string][] {
  const out: [string, string][] = [["PATH", servicePath(s.env.PATH)]];
  for (const key of ["LANG", "LC_ALL"]) {
    const value = s.env[key];
    if (value) out.push([key, value]);
  }
  // The shell's management CLI must find the same state home and Pi sources.
  const state = s.env.XDG_STATE_HOME;
  if (state && isAbsolute(state)) out.push(["XDG_STATE_HOME", state]);
  if (s.env.PI_CODING_AGENT_DIR)
    out.push(["PI_CODING_AGENT_DIR", agentDirectory(s)]);
  return out;
}
export function checked(value: string): string {
  // biome-ignore lint/suspicious/noControlCharactersInRegex: definitions cannot carry controls
  if (/[\u0000-\u001f\u007f]/.test(value)) throw new ContractError("invalid");
  return value;
}
const specifiers = (value: string) => checked(value).replaceAll("%", "%%");
const quoted = (value: string) =>
  `"${specifiers(value).replace(/["\\]/g, "\\$&")}"`;
// Command lines also substitute $NAME; $$ is a literal dollar.
const argument = (value: string) => quoted(value).replaceAll("$", "$$$$");

export interface UnitInput {
  node: string;
  cli: string;
  workspace: string;
  /** The port and token file `server install` creates. */
  serverConfig: string;
  agentDir: string;
  sdk: string[];
  environment: [string, string][];
}
export function buildUnit(u: UnitInput): string {
  const command = (args: string[]) =>
    [u.node, u.cli, ...args].map(argument).join(" ");
  return [
    `${MARKER}; \`cadence server install\` and \`restart\` rewrite this file.`,
    "# Override with `systemctl --user edit cadence`; opt out with `systemctl --user disable --now cadence` or `mask`.",
    "[Unit]",
    "Description=Cadence shared task service and WebUI",
    "Documentation=https://github.com/abelxiaoxing/cadence/blob/main/docs/service-management.md",
    `ConditionPathExists=${specifiers(u.cli)}`,
    // A new owner without Pi's auth source or SDK would quarantine; wait instead.
    `ConditionPathExists=${specifiers(join(u.agentDir, "auth.json"))}`,
    ...u.sdk.map((path) => `ConditionPathExists=${specifiers(path)}`),
    "StartLimitIntervalSec=300",
    "StartLimitBurst=3",
    "",
    "[Service]",
    "Type=simple",
    `WorkingDirectory=${specifiers(u.workspace)}`,
    ...u.environment.map(([k, v]) => `Environment=${quoted(`${k}=${v}`)}`),
    `ExecStart=${command(["start", "--foreground", "--workspace", u.workspace, "--server-config", u.serverConfig])}`,
    // Authenticated orderly Stop first. Mixed mode signals only the management
    // client, so a settling owner is never sent SIGTERM by systemd.
    `ExecStop=-${command(["stop", "--workspace", u.workspace])}`,
    "KillMode=mixed",
    "TimeoutStopSec=90",
    "Restart=on-failure",
    "RestartSec=10",
    "",
    "[Install]",
    "WantedBy=default.target",
    "",
  ].join("\n");
}
/** undefined: absent; null: present but not ours (or not a regular file).
 * A UTF-16LE byte-order mark selects that encoding (Windows launchers). */
export function readGenerated(
  path: string,
  marker: string,
): string | undefined | null {
  try {
    if (!lstatSync(path).isFile()) return null;
    const bytes = readFileSync(path);
    const text =
      bytes[0] === 0xff && bytes[1] === 0xfe
        ? bytes.subarray(2).toString("utf16le")
        : bytes.toString("utf8");
    return text.startsWith(marker) ? text : null;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    throw error;
  }
}
function unitWorkspace(text: string | undefined): string | undefined {
  return text?.match(/^WorkingDirectory=(.+)$/m)?.[1].replaceAll("%%", "%");
}
function directory(path: string): boolean {
  try {
    return isAbsolute(path) && statSync(path).isDirectory();
  } catch {
    return false;
  }
}
/** The state home the service's owner will use (XDG_STATE_HOME is baked). */
function serviceStateHome(s: AutostartSystem): string {
  const state =
    s.platform === "win32" ? s.env.LOCALAPPDATA : s.env.XDG_STATE_HOME;
  return state && isAbsolute(state)
    ? state
    : join(
        s.home,
        ...(s.platform === "win32"
          ? ["AppData", "Local"]
          : [".local", "state"]),
      );
}
/** An explicit workspace, else the one the existing definition runs, else ~/cadence. */
export function selectWorkspace(
  s: AutostartSystem,
  requested: string | undefined,
  kept: string | undefined,
): { workspace: string; redirectedFrom?: string } {
  let chosen: string | undefined;
  if (requested) {
    chosen = expandHome(requested, s.home);
    if (!directory(chosen)) throw new ContractError("invalid");
    chosen = resolve(chosen);
  } else if (kept && directory(kept)) chosen = kept;
  const landing = chosen
    ? effectiveWorkspace(chosen, serviceStateHome(s), s.home)
    : { workspace: join(s.home, LANDING_WORKSPACE), redirected: false };
  if (landing.workspace !== chosen)
    mkdirSync(landing.workspace, { recursive: true });
  return landing.redirected
    ? { workspace: landing.workspace, redirectedFrom: chosen }
    : { workspace: landing.workspace };
}
export function write(path: string, content: string | Buffer): void {
  mkdirSync(dirname(path), { recursive: true });
  const temporary = `${path}.${process.pid}.tmp`;
  try {
    writeFileSync(temporary, content, { mode: 0o644, flag: "wx" });
    renameSync(temporary, path);
  } finally {
    rmSync(temporary, { force: true });
  }
}
export function regularFile(path: string): boolean {
  try {
    return statSync(path).isFile();
  } catch {
    return false;
  }
}
/** A service manager that only signals would end a running owner without the
 * authenticated Stop, so stop it orderly first; undefined once nothing runs. */
export async function settle(
  s: AutostartSystem,
  workspace: string | undefined,
): Promise<AutostartResult | undefined> {
  if (!workspace) return;
  const status = await s.stopOwner(workspace);
  if (status === "stopped") return;
  // Anything but a confirmed Stop, including one still settling, is a refusal.
  return {
    status:
      status === "quarantined" || status === "unavailable"
        ? status
        : "unconfirmed",
    workspace,
  };
}
/** A user unit in default.target starts with the user manager: at login, or
 * at boot once logind lingers the user. */
function bootStart(
  s: AutostartSystem,
  attempt: boolean,
): { linger?: LingerState } {
  const current = s.linger();
  if (current === undefined) return {};
  if (current) return { linger: "on" };
  if (!attempt) return { linger: "off" };
  // Unprompted first; only when logind needs authorization may it ask.
  return {
    linger:
      s.enableLinger(false) || s.enableLinger(true) ? "enabled" : "refused",
  };
}
/** install: registers from any package location, enables unless masked (also
 * a disabled unit) and enables linger for boot start unless `linger` is false.
 * restart: rewrites an existing unit with the current Node and package paths,
 * keeping its workspace, enablement and linger, and starts it unless masked. */
export function configureAutostart(
  s: AutostartSystem,
  mode: "install" | "restart",
  requested?: string,
  linger = false,
): AutostartResult {
  if (s.platform !== "linux") return { status: "unsupported" };
  if (s.systemctl(["show-environment"]).status !== 0)
    return { status: "unavailable" };
  const path = unitPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (mode === "restart" && previous === undefined) return { status: "absent" };
  // Written only when the SDK resolves; an owner without it would quarantine.
  const sdk = sdkPackages(s.root);
  if (!sdk) return { status: "missing-pi-sdk" };
  const { workspace, redirectedFrom } = selectWorkspace(
    s,
    requested,
    unitWorkspace(previous),
  );
  const agentDir = agentDirectory(s);
  const content = buildUnit({
    node: s.node,
    cli: join(s.root, "src", "service-cli.mjs"),
    workspace,
    serverConfig: serverConfigPath(s.home),
    agentDir,
    sdk,
    environment: serviceEnvironment(s),
  });
  const enabled = s.systemctl(["is-enabled", s.unit]).stdout.trim();
  const active = s.systemctl(["is-active", "--quiet", s.unit]).status === 0;
  // Stop with the loaded definition, so a changed workspace or Node path still
  // reaches the old owner's orderly ExecStop before the file is replaced.
  if (active) s.systemctl(["stop", s.unit]);
  write(path, content);
  s.systemctl(["daemon-reload"]);
  const result = {
    unit: path,
    workspace,
    ...(redirectedFrom ? { redirectedFrom } : {}),
  };
  if (enabled.startsWith("masked")) return { status: "masked", ...result };
  if (
    mode === "install" &&
    enabled !== "enabled" &&
    s.systemctl(["enable", s.unit]).status !== 0
  )
    return { status: "failed", ...result };
  // Linger may prompt, so it runs after the start: an interrupted prompt must
  // not leave the owner stopped above.
  const boot = () => (mode === "install" ? bootStart(s, linger) : {});
  if (!regularFile(join(agentDir, "auth.json")))
    return { status: "waiting-for-pi-login", ...result, ...boot() };
  s.systemctl(["reset-failed", s.unit]);
  const started = s.systemctl(["start", s.unit]).status === 0;
  return { status: started ? "started" : "failed", ...result, ...boot() };
}
/** ExecStop is the authenticated orderly Stop; the unit stays enabled. */
export function stopAutostart(s: AutostartSystem): AutostartResult {
  if (s.platform !== "linux") return { status: "unsupported" };
  const path = unitPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  if (s.systemctl(["show-environment"]).status !== 0)
    return { status: "unavailable", unit: path };
  return {
    status: s.systemctl(["stop", s.unit]).status === 0 ? "stopped" : "failed",
    unit: path,
    workspace: unitWorkspace(previous),
  };
}
/** Disable through ExecStop's orderly route, then delete only our own file.
 * Workspace, state home, linger and Pi sources stay untouched. */
export function removeAutostart(s: AutostartSystem): AutostartResult {
  if (s.platform !== "linux") return { status: "unsupported" };
  const path = unitPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  if (s.systemctl(["show-environment"]).status !== 0)
    return { status: "unavailable", unit: path };
  if (s.systemctl(["disable", "--now", s.unit]).status !== 0)
    return { status: "failed", unit: path };
  rmSync(path);
  s.systemctl(["daemon-reload"]);
  s.systemctl(["reset-failed", s.unit]);
  return { status: "removed", unit: path };
}
export function autostartStatus(s: AutostartSystem): AutostartResult {
  if (s.platform !== "linux") return { status: "unsupported" };
  const path = unitPath(s);
  const previous = readGenerated(path, MARKER);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  return {
    status: s.systemctl(["is-active", s.unit]).stdout.trim() || "unknown",
    enabled: s.systemctl(["is-enabled", s.unit]).stdout.trim() || "unknown",
    unit: path,
    workspace: unitWorkspace(previous),
    ...bootStart(s, false),
  };
}
