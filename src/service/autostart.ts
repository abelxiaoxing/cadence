/** Linux systemd user unit for the shared owner. Management-only and SDK-free:
 * it writes one generated unit file and drives `systemctl --user`; it never
 * signals owners, edits state homes, deletes locks or repairs quarantine. */
import { spawnSync } from "node:child_process";
import {
  lstatSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { delimiter, dirname, isAbsolute, join, resolve, sep } from "node:path";
import { ContractError } from "../service-contract.ts";
import { effectiveWorkspace, LANDING_WORKSPACE } from "../task-store.ts";

export const UNIT = "cadence.service";
const MARKER = "# Generated by @abelxiaoxing/cadence";

export interface AutostartSystem {
  platform: NodeJS.Platform;
  env: NodeJS.ProcessEnv;
  home: string;
  node: string;
  /** Package root containing src/service-cli.mjs. */
  root: string;
  unit: string;
  systemctl(args: string[]): { status: number | null; stdout: string };
  linger(): boolean | undefined;
}
export interface AutostartResult {
  status: string;
  unit?: string;
  workspace?: string;
  redirectedFrom?: string;
  enabled?: string;
}
export function hostSystem(root: string): AutostartSystem {
  const run = (command: string, args: string[]) => {
    const r = spawnSync(command, args, {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
    return { status: r.error ? null : r.status, stdout: r.stdout ?? "" };
  };
  return {
    platform: process.platform,
    env: process.env,
    home: homedir(),
    node: process.execPath,
    root,
    unit: UNIT,
    systemctl: (args) => run("systemctl", ["--user", ...args]),
    linger: () => {
      const r = run("loginctl", [
        "show-user",
        String(process.getuid?.()),
        "--property=Linger",
        "--value",
      ]);
      return r.status === 0 ? r.stdout.trim() === "yes" : undefined;
    },
  };
}
function expandHome(value: string, home: string): string {
  if (value === "~") return home;
  return value.startsWith("~/") ? join(home, value.slice(2)) : value;
}
/** Same selection as Pi's getAgentDir: PI_CODING_AGENT_DIR or ~/.pi/agent. */
export function agentDirectory(s: AutostartSystem): string {
  const selected = s.env.PI_CODING_AGENT_DIR;
  return resolve(
    selected ? expandHome(selected, s.home) : join(s.home, ".pi", "agent"),
  );
}
/** Only Pi's user-scope npm layout; project, temporary, global and checkout
 * installs are not Pi's managed user package and are left alone. */
export function piUserInstall(s: AutostartSystem): boolean {
  try {
    const managed = join(
      agentDirectory(s),
      "npm",
      "node_modules",
      "@abelxiaoxing",
      "cadence",
    );
    return realpathSync(managed) === realpathSync(s.root);
  } catch {
    return false;
  }
}
/** The host bundle imports these by bare specifier. Pi installs packages with
 * --legacy-peer-deps, so they exist only if something else provides them; an
 * owner that cannot load them quarantines, so never autostart without them. */
export function sdkPackages(root: string): string[] | undefined {
  let start: string;
  try {
    start = realpathSync(join(root, "src"));
  } catch {
    return undefined;
  }
  const found: string[] = [];
  for (const name of ["pi-coding-agent", "pi-ai"]) {
    let hit: string | undefined;
    for (let dir = start; !hit; dir = dirname(dir)) {
      const candidate = join(
        dir,
        "node_modules",
        "@earendil-works",
        name,
        "package.json",
      );
      if (regularFile(candidate)) hit = candidate;
      else if (dirname(dir) === dir) return undefined;
    }
    found.push(hit);
  }
  return found;
}
/** Package-owned units live in the user data path, so `systemctl --user mask`
 * and `edit` in ~/.config/systemd/user keep overriding what upgrades rewrite. */
export function unitPath(s: AutostartSystem): string {
  const data = s.env.XDG_DATA_HOME;
  return join(
    data && isAbsolute(data) ? data : join(s.home, ".local", "share"),
    "systemd",
    "user",
    s.unit,
  );
}
/** npm prepends lifecycle bins to PATH; bake only the user's own search path. */
export function servicePath(value: string | undefined): string {
  const kept = (value ?? "")
    .split(delimiter)
    .filter(
      (entry) =>
        isAbsolute(entry) &&
        !entry.endsWith(`${sep}node_modules${sep}.bin`) &&
        !entry.includes(`${sep}node-gyp-bin`),
    );
  return kept.length
    ? [...new Set(kept)].join(delimiter)
    : "/usr/local/bin:/usr/bin:/bin";
}
function serviceEnvironment(s: AutostartSystem): [string, string][] {
  const out: [string, string][] = [["PATH", servicePath(s.env.PATH)]];
  for (const key of ["LANG", "LC_ALL"]) {
    const value = s.env[key];
    if (value) out.push([key, value]);
  }
  // The shell's management CLI must find the same state home and Pi sources.
  const state = s.env.XDG_STATE_HOME;
  if (state && isAbsolute(state)) out.push(["XDG_STATE_HOME", state]);
  if (s.env.PI_CODING_AGENT_DIR)
    out.push(["PI_CODING_AGENT_DIR", agentDirectory(s)]);
  return out;
}
function checked(value: string): string {
  // biome-ignore lint/suspicious/noControlCharactersInRegex: unit lines cannot carry controls
  if (/[\u0000-\u001f\u007f]/.test(value)) throw new ContractError("invalid");
  return value;
}
const specifiers = (value: string) => checked(value).replaceAll("%", "%%");
const quoted = (value: string) =>
  `"${specifiers(value).replace(/["\\]/g, "\\$&")}"`;
// Command lines also substitute $NAME; $$ is a literal dollar.
const argument = (value: string) => quoted(value).replaceAll("$", "$$$$");

export interface UnitInput {
  node: string;
  cli: string;
  workspace: string;
  agentDir: string;
  sdk: string[];
  environment: [string, string][];
}
export function buildUnit(u: UnitInput): string {
  const command = (args: string[]) =>
    [u.node, u.cli, ...args].map(argument).join(" ");
  return [
    `${MARKER} on Pi package install/update; upgrades rewrite this file.`,
    "# Override with `systemctl --user edit cadence`; opt out with `systemctl --user disable --now cadence` or `mask`.",
    "[Unit]",
    "Description=Cadence shared task service and WebUI",
    "Documentation=https://github.com/abelxiaoxing/cadence/blob/main/docs/service-management.md",
    `ConditionPathExists=${specifiers(u.cli)}`,
    // A new owner without Pi's auth source or SDK would quarantine; wait instead.
    `ConditionPathExists=${specifiers(join(u.agentDir, "auth.json"))}`,
    ...u.sdk.map((path) => `ConditionPathExists=${specifiers(path)}`),
    "StartLimitIntervalSec=300",
    "StartLimitBurst=3",
    "",
    "[Service]",
    "Type=simple",
    `WorkingDirectory=${specifiers(u.workspace)}`,
    ...u.environment.map(([k, v]) => `Environment=${quoted(`${k}=${v}`)}`),
    `ExecStart=${command(["start", "--foreground", "--workspace", u.workspace])}`,
    // Authenticated orderly Stop first. Mixed mode signals only the management
    // client, so a settling owner is never sent SIGTERM by systemd.
    `ExecStop=-${command(["stop", "--workspace", u.workspace])}`,
    "KillMode=mixed",
    "TimeoutStopSec=90",
    "Restart=on-failure",
    "RestartSec=10",
    "",
    "[Install]",
    "WantedBy=default.target",
    "",
  ].join("\n");
}
/** undefined: absent; null: present but not ours (or not a regular file). */
function readGenerated(path: string): string | undefined | null {
  try {
    if (!lstatSync(path).isFile()) return null;
    const text = readFileSync(path, "utf8");
    return text.startsWith(MARKER) ? text : null;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    throw error;
  }
}
function generatedWorkspace(text: string | undefined): string | undefined {
  return text?.match(/^WorkingDirectory=(.+)$/m)?.[1].replaceAll("%%", "%");
}
function directory(path: string): boolean {
  try {
    return isAbsolute(path) && statSync(path).isDirectory();
  } catch {
    return false;
  }
}
/** The state home the unit's owner will use (XDG_STATE_HOME is baked). */
function unitStateHome(s: AutostartSystem): string {
  const state = s.env.XDG_STATE_HOME;
  return state && isAbsolute(state) ? state : join(s.home, ".local", "state");
}
function selectWorkspace(
  s: AutostartSystem,
  requested: string | undefined,
  previous: string | undefined,
): { workspace: string; redirectedFrom?: string } {
  let chosen: string | undefined;
  if (requested) {
    chosen = expandHome(requested, s.home);
    if (!directory(chosen)) throw new ContractError("invalid");
    chosen = resolve(chosen);
  } else {
    const kept = generatedWorkspace(previous);
    if (kept && directory(kept)) chosen = kept;
  }
  const landing = chosen
    ? effectiveWorkspace(chosen, unitStateHome(s), s.home)
    : { workspace: join(s.home, LANDING_WORKSPACE), redirected: false };
  if (landing.workspace !== chosen)
    mkdirSync(landing.workspace, { recursive: true });
  return landing.redirected
    ? { workspace: landing.workspace, redirectedFrom: chosen }
    : { workspace: landing.workspace };
}
function write(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  const temporary = `${path}.${process.pid}.tmp`;
  try {
    writeFileSync(temporary, content, { mode: 0o644, flag: "wx" });
    renameSync(temporary, path);
  } finally {
    rmSync(temporary, { force: true });
  }
}
function regularFile(path: string): boolean {
  try {
    return statSync(path).isFile();
  } catch {
    return false;
  }
}
/** refresh: Pi install/update hook (opt-out and user disable/mask respected).
 * install: explicit command from any location; enables unless masked. */
export function configureAutostart(
  s: AutostartSystem,
  mode: "refresh" | "install",
  requested?: string,
): AutostartResult {
  if (s.platform !== "linux") return { status: "skipped" };
  if (
    mode === "refresh" &&
    (s.env.CADENCE_AUTOSTART === "0" || !piUserInstall(s))
  )
    return { status: "skipped" };
  if (s.systemctl(["show-environment"]).status !== 0)
    return { status: "unavailable" };
  const path = unitPath(s);
  const previous = readGenerated(path);
  if (previous === null) return { status: "foreign", unit: path };
  // Written only when the SDK resolves, so a later refresh after it appears is
  // still a first registration rather than a user's disabled unit.
  const sdk = sdkPackages(s.root);
  if (!sdk) return { status: "missing-pi-sdk" };
  const { workspace, redirectedFrom } = selectWorkspace(
    s,
    requested ?? s.env.CADENCE_WORKSPACE,
    previous,
  );
  const agentDir = agentDirectory(s);
  const content = buildUnit({
    node: s.node,
    cli: join(s.root, "src", "service-cli.mjs"),
    workspace,
    agentDir,
    sdk,
    environment: serviceEnvironment(s),
  });
  const enabled = s.systemctl(["is-enabled", s.unit]).stdout.trim();
  const active = s.systemctl(["is-active", "--quiet", s.unit]).status === 0;
  // Stop with the loaded definition, so a changed workspace or Node path still
  // reaches the old owner's orderly ExecStop before the file is replaced.
  if (active) s.systemctl(["stop", s.unit]);
  write(path, content);
  s.systemctl(["daemon-reload"]);
  const result = {
    unit: path,
    workspace,
    ...(redirectedFrom ? { redirectedFrom } : {}),
  };
  if (enabled.startsWith("masked")) return { status: "masked", ...result };
  const wanted =
    mode === "install" || previous === undefined || enabled === "enabled";
  if (
    wanted &&
    enabled !== "enabled" &&
    s.systemctl(["enable", s.unit]).status !== 0
  )
    return { status: "failed", ...result };
  if (!wanted && !active) return { status: "disabled", ...result };
  if (!regularFile(join(agentDir, "auth.json")))
    return { status: "waiting-for-pi-login", ...result };
  s.systemctl(["reset-failed", s.unit]);
  const started = s.systemctl(["start", s.unit]).status === 0;
  return { status: started ? "started" : "failed", ...result };
}
/** Disable through ExecStop's orderly route, then delete only our own file.
 * Workspace, state home and Pi sources stay untouched. */
export function removeAutostart(s: AutostartSystem): AutostartResult {
  if (s.platform !== "linux") return { status: "skipped" };
  const path = unitPath(s);
  const previous = readGenerated(path);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  if (s.systemctl(["show-environment"]).status !== 0)
    return { status: "unavailable", unit: path };
  if (s.systemctl(["disable", "--now", s.unit]).status !== 0)
    return { status: "failed", unit: path };
  rmSync(path);
  s.systemctl(["daemon-reload"]);
  s.systemctl(["reset-failed", s.unit]);
  return { status: "removed", unit: path };
}
export function autostartStatus(s: AutostartSystem): AutostartResult {
  if (s.platform !== "linux") return { status: "skipped" };
  const path = unitPath(s);
  const previous = readGenerated(path);
  if (previous === null) return { status: "foreign", unit: path };
  if (previous === undefined) return { status: "absent" };
  return {
    status: s.systemctl(["is-active", s.unit]).stdout.trim() || "unknown",
    enabled: s.systemctl(["is-enabled", s.unit]).stdout.trim() || "unknown",
    unit: path,
    workspace: generatedWorkspace(previous),
  };
}
