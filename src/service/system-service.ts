/** Explicit Linux system-manager registration. Runs as root without logind or
 * a user bus. No sudo, credential copying, process killing or fence recovery. */
import { existsSync, realpathSync, rmSync } from "node:fs";
import { isAbsolute, join } from "node:path";
import {
  type AutostartResult,
  type AutostartSystem,
  agentDirectory,
  buildUnit,
  readGenerated,
  regularFile,
  sdkPackages,
  selectWorkspace,
  serviceConfigPath,
  serviceEnvironment,
  settle,
  unitPath,
  unitWorkspace,
  write,
} from "./autostart.ts";

const MARKER = "# Generated by @abelxiaoxing/cadence";
function boundary(s: AutostartSystem): AutostartResult | undefined {
  if (s.platform !== "linux" || s.scope !== "system")
    return { status: "unsupported" };
  if (s.uid !== 0) return { status: "root-required", scope: "system" };
}
function legacyPath(s: AutostartSystem): string {
  return unitPath({ ...s, scope: "user", unitDirectory: undefined });
}
function observed(s: AutostartSystem) {
  const path = unitPath(s);
  let previous = readGenerated(path, MARKER);
  if (
    typeof previous === "string" &&
    ((unitWorkspace(previous) !== null &&
      !isAbsolute(unitWorkspace(previous) ?? "")) ||
      !previous.includes("\nUser=root\n"))
  )
    previous = null;
  const result = { unit: path, scope: "system" as const };
  return { path, previous, result };
}
function masked(s: AutostartSystem): boolean {
  return s.systemctl(["is-enabled", s.unit]).stdout.trim().startsWith("masked");
}

/** The management CLI must observe the same private namespace the generated
 * unit used. A changed HOME/XDG source is not proof that its old owner is absent. */
function sameStateEnvironment(s: AutostartSystem, previous: string): boolean {
  try {
    const values = new Map<string, string>();
    for (const line of previous.split("\n")) {
      if (!line.startsWith("Environment=")) continue;
      const value: unknown = JSON.parse(line.slice("Environment=".length));
      if (typeof value !== "string") return false;
      const at = value.indexOf("=");
      const key = value.slice(0, at);
      if (key !== "HOME" && key !== "XDG_STATE_HOME") continue;
      if (values.has(key)) return false;
      values.set(key, value.slice(at + 1).replaceAll("%%", "%"));
    }
    const state = s.env.XDG_STATE_HOME;
    return (
      values.get("HOME") === s.home &&
      values.get("XDG_STATE_HOME") ===
        (state && isAbsolute(state) ? state : undefined)
    );
  } catch {
    return false;
  }
}

/** A kept definition is not evidence that an inactive manager owns the current
 * directory owner. Refuse detached/uncertain owners without sending them Stop. */
async function ownerBoundary(
  s: AutostartSystem,
  workspace: string | null,
  managed: boolean,
): Promise<AutostartResult | undefined> {
  const status = await s.ownerStatus(workspace, serviceConfigPath(s));
  if (managed) {
    if (status === "absent") return { status: "unavailable", workspace };
  } else if (status !== "absent" && status !== "stopped") {
    return {
      status: status === "alive" ? "project-running" : "unavailable",
      workspace,
    };
  }
}

export async function configureSystemService(
  s: AutostartSystem,
  mode: "install" | "restart",
  requested?: string,
): Promise<AutostartResult> {
  const refused = boundary(s);
  if (refused) return refused;
  // Never silently abandon or replace a previously installed user manager.
  if (existsSync(legacyPath(s)))
    return { status: "scope-conflict", unit: legacyPath(s), scope: "system" };
  if (s.systemctl(["show-environment"]).status !== 0)
    return { status: "unavailable", scope: "system" };
  const { path, previous, result } = observed(s);
  if (masked(s)) return { status: "masked", ...result };
  if (previous === null) return { status: "foreign", ...result };
  if (mode === "restart" && previous === undefined)
    return { status: "absent", scope: "system" };
  const sdk = sdkPackages(s.root);
  // A missing kept project is not permission to silently replace it with a
  // different landing directory on restart.
  if (
    previous &&
    unitWorkspace(previous) &&
    !existsSync(unitWorkspace(previous) as string)
  )
    return { status: "workspace-changed", ...result };
  // Validate the target without creating it or disturbing the previous owner.
  const selected = selectWorkspace(
    s,
    requested,
    mode === "install" && requested === undefined
      ? null
      : unitWorkspace(previous),
    false,
  );
  if (selected.workspace !== null && !sdk)
    return { status: "missing-pi-sdk", scope: "system" };
  const selectedReal =
    selected.workspace && existsSync(selected.workspace)
      ? realpathSync(selected.workspace)
      : undefined;
  const agentDir = agentDirectory(s);
  const content = buildUnit({
    system: true,
    node: s.node,
    cli: join(s.root, "src", "service-cli.mjs"),
    workspace: selected.workspace,
    serverConfig: serviceConfigPath(s),
    agentDir,
    sdk: sdk ?? [],
    environment: serviceEnvironment(s),
  });
  if (previous && !sameStateEnvironment(s, previous))
    return { status: "environment-changed", ...result };
  const active = s.systemctl(["is-active", "--quiet", s.unit]);
  if (
    active.status !== 0 &&
    active.status !== 3 &&
    !(active.status === 4 && previous === undefined)
  )
    return { status: "unavailable", ...result };
  if (active.status === 0 && previous === undefined)
    return { status: "foreign", ...result };
  if (
    (selected.workspace === null || selectedReal) &&
    (previous === undefined || selected.workspace !== unitWorkspace(previous))
  ) {
    const target = await ownerBoundary(s, selected.workspace, false);
    if (target) return { ...selected, ...target, ...result };
  }
  const workspace = unitWorkspace(previous);
  if (workspace !== undefined) {
    const refused = await ownerBoundary(s, workspace, active.status === 0);
    if (refused) return { ...refused, ...result };
  }
  // For an inactive unit, never Stop an owner that could have appeared after
  // the observation above. A concurrent detached launch must collide with the
  // new owner's reservation instead, not be stopped/adopted by this command.
  const unsettled =
    active.status === 0 ? await settle(s, workspace) : undefined;
  if (unsettled) return { ...unsettled, ...result };
  if (readGenerated(path, MARKER) !== previous)
    return { status: "foreign", ...result };
  if (selectedReal && selected.workspace) {
    try {
      if (realpathSync(selected.workspace) !== selectedReal)
        return { status: "workspace-changed", ...result };
    } catch {
      return { status: "workspace-changed", ...result };
    }
  }
  // Stop with the loaded definition, but only after exact native Stop has
  // settled. systemctl's timeout/SIGKILL must never become our safety proof.
  if (active.status === 0 && s.systemctl(["stop", s.unit]).status !== 0)
    return {
      status: "unconfirmed",
      workspace: unitWorkspace(previous),
      ...result,
    };
  write(path, content);
  if (s.systemctl(["daemon-reload"]).status !== 0)
    return { status: "failed", ...result, ...selected };
  if (mode === "install" && s.systemctl(["enable", s.unit]).status !== 0)
    return { status: "failed", ...result, ...selected };
  // A restart does not change enablement or masking; a disabled unit can be
  // started explicitly now but stays disabled at boot, like the user route.
  if (selected.workspace !== null && !regularFile(join(agentDir, "auth.json")))
    return { status: "waiting-for-pi-login", ...result, ...selected };
  s.systemctl(["reset-failed", s.unit]);
  return {
    status: s.systemctl(["start", s.unit]).status === 0 ? "started" : "failed",
    ...result,
    ...selected,
  };
}

export async function stopSystemService(
  s: AutostartSystem,
  remove = false,
): Promise<AutostartResult> {
  const refused = boundary(s);
  if (refused) return refused;
  const { path, previous, result } = observed(s);
  // A mask is an administrator-owned override, never a generated file.
  if (previous === null)
    return { status: masked(s) ? "masked" : "foreign", ...result };
  if (previous === undefined) return { status: "absent", scope: "system" };
  if (s.systemctl(["show-environment"]).status !== 0)
    return { status: "unavailable", ...result };
  const workspace = unitWorkspace(previous);
  if (!sameStateEnvironment(s, previous))
    return { status: "environment-changed", workspace, ...result };
  const active = s.systemctl(["is-active", "--quiet", s.unit]);
  if (active.status !== 0 && active.status !== 3)
    return { status: "unavailable", workspace, ...result };
  const owner = await ownerBoundary(
    s,
    workspace as string | null,
    active.status === 0,
  );
  if (owner) return { ...owner, ...result };
  const unsettled =
    active.status === 0 ? await settle(s, workspace) : undefined;
  if (unsettled) return { ...unsettled, ...result };
  if (readGenerated(path, MARKER) !== previous)
    return { status: "foreign", ...result };
  if (active.status === 0 && s.systemctl(["stop", s.unit]).status !== 0)
    return { status: "unconfirmed", workspace, ...result };
  if (!remove) return { status: "stopped", workspace, ...result };
  if (s.systemctl(["disable", s.unit]).status !== 0)
    return { status: "failed", workspace, ...result };
  // Recheck generated bytes after awaited owner control. Preserve external edits.
  if (readGenerated(path, MARKER) !== previous)
    return { status: "foreign", ...result };
  rmSync(path);
  if (s.systemctl(["daemon-reload"]).status !== 0)
    return { status: "failed", ...result };
  s.systemctl(["reset-failed", s.unit]);
  return { status: "removed", ...result };
}

export function systemServiceStatus(s: AutostartSystem): AutostartResult {
  const refused = boundary(s);
  if (refused) return refused;
  const { previous, result } = observed(s);
  if (previous === undefined) return { status: "absent", scope: "system" };
  const enabled =
    s.systemctl(["is-enabled", s.unit]).stdout.trim() || "unknown";
  if (enabled.startsWith("masked"))
    return { status: "masked", enabled, ...result };
  if (previous === null) return { status: "foreign", ...result };
  return {
    status: s.systemctl(["is-active", s.unit]).stdout.trim() || "unknown",
    enabled,
    workspace: unitWorkspace(previous),
    ...result,
  };
}
